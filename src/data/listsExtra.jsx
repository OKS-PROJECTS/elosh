const name = (key = 'name', subKey) => ({
  key,
  header: 'Name',
  sortable: true,
  render: (r) => <EntityCell name={r[key]} sub={subKey ? r[subKey] : undefined} src={r.avatar} />,
})
const status = { key: 'status', header: 'Status', render: (r) => <StatusChip status={r.status} /> }
const text = (key, header, opts = {}) => ({ key, header, sortable: opts.sortable ?? false, ...opts })
const dateCol = (key, header) => ({ key, header, sortable: true, render: (r) => date(r[key]) })
const moneyCol = (key, header) => ({
  key,
  header,
  align: 'end',
  sortable: true,
  sortValue: (r) => r[key],
  render: (r) => money(r[key]),
})

